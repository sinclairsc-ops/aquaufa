					<div class="center-block">						<div id="chars-page-info" class="content-text">
												
 
<p align="justify">В нашем Аквапарке лето и веселье круглый год! Здесь созданы все условия для полноценного и активного отдыха. Уникальный дизайн позволит окунуться в затерянный мир Юрского периода! 12 водных горок подарят отличное настроение, а различные водные аттракционы и бассейны позволят поплавать на огромных волнах или расслабиться тихой лагуне. </p>
 
<p align="justify">Семьи с маленькими детьми смогут весело провести время в детских игровых городках, школьники увлекутся поиском горок, спрятанных в пещерах и динозаврах, активная молодёжь сможет испытать экстремальные горки, люди старшего возраста расслабятся и улучшат здоровье в СПА комплексе с джакузи, саунами и хамамом.</p>
 
<p align="justify"> </p>
 
<p align="justify"><b>Водные горки:</b></p>
 
<p align="justify"> </p>
 
<div align="justify">
  <ul>
    <li>&laquo;Свободное падение&raquo; и &laquo;Камикадзе&raquo; - горки предназначены для любителей острых ощущений, их названия говорят сами за себя.</li>
  
    <li>Горки &laquo;Быстрая река&raquo;, &laquo;Горный ручей&raquo; и &laquo;Анаконда&raquo; гарантируют незабываемые ощущения во время стремительного спуска и поворотов на 180 и 360 градусов.</li>
  
    <li>Горка &laquo;Водоворот&raquo; - одна из самых экстремальных горок, в которой скольжение по закрытой трубе заканчивается вращением в огромной воронке и попаданием в бассейн.</li>
  
    <li>Горки для посетителей младшего возраста задекорированы и расположены внутри динозавров, скал и пещер. </li>
  
    <li>2 горки находятся внутри огромного гнезда, это веселые горки, стремительный спуск с которых дарит радость и хорошее настроение.</li>
  
    <li>Горки &laquo;Плюх&raquo; и &laquo;Бултых&raquo; - размещаются внутри таинственной пещеры и огромного динозавра, их посещение станет настоящим приключением для маленьких посетителей аквапарка, а спуск с крутыми поворотами доставит немало радости. </li>
  
    <li>Горка &laquo;Динь-динь&raquo; расположена внутри веселого динозавра, это горка для смелых и отважных посетителей, которые готовые к веселым приключениям. </li>
  
    <li>Горка на летней террасе (работает в летнее время) скрыта внутри доброго динозаврика и предназначена наших маленьких посетителей. </li>
  </ul>
</div>
 
<p align="justify"> </p>
 
<p align="justify"><b>В Аквапарке представлены различные водные аттракционы и бассейны:</b></p>
 
<div align="justify">
  <ul>
    <li> Волновой бассейн с периодическим движением воды, воссоздает настоящие морские волны. </li>
  
    <li> Relax-бассейн предназначен для тех посетителей, которые хотят расслабиться и уединиться, купаясь, посетители смогут воспользоваться услугами аква-бара, отдохнуть в джакузи, под струйным массажем или живописным водопадом, </li>
  
    <li> Развлекательный бассейн, стилизованный под тропическое озеро с динозаврами, расположен в самом центре аквапарка и предназначен для активных игр в воде. </li>
  
    <li> Медленная река, окружающая озеро, благодаря своему центральному расположению позволит отдохнуть, проплывая мимо самых красивых уголков аквапарка.</li>
  </ul>
</div>
 
<p align="justify"><b>Детские игровые площадки:</b></p>
 
<p align="justify">2 детские игровые площадки предназначены для посетителей с детьми: большой детский игровой городок с горками и бассейном на территории аквапарка, а также горка и плескательный бассейн на террасе (работает в летнее время).</p>
 
<p align="justify"> </p>
 
<p align="justify"><b>СПА комплекс</b> включает джакузи, 3 сауны (с различными температурными режимами), хамам, холодные ванны и контрастные души. С помощью уникального дизайна в этой зоне создана экзотическая атмосфера вулканической пещеры.</p>
 
